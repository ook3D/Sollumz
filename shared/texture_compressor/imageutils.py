import os
from pathlib import Path

import bpy
from bpy.types import Image


def texture_extension(image: Image) -> str:
    """The file extension of `image`'s filepath (including the dot, e.g. `.png`), or `""`."""
    return os.path.splitext(bpy.path.basename(image.filepath))[1]


def is_dds_image(image: Image) -> bool:
    """Whether `image` is already a DDS texture: packed DDS data, or a `.dds` file path."""
    packed = image.packed_file
    if packed and (data := packed.data):
        return data[:4] == b"DDS "
    if is_generated_image(image):
        return False
    return texture_extension(image).lower() == ".dds"


def is_generated_image(image: Image) -> bool:
    """Whether `image` only exists in memory: generated by Blender, and neither saved nor packed, so its pixels have no
    file backing them.
    """
    return image.source == "GENERATED" and not image.packed_file


def image_has_alpha(image: Image) -> bool:
    """Whether `image` has any pixel that is not fully opaque (alpha below 255).

    An image whose alpha is ignored (`alpha_mode == "NONE"`) or that has no alpha channel is opaque. Otherwise
    every pixel is checked, as images commonly have an alpha channel that is fully opaque.
    """
    if image.alpha_mode == "NONE" or image.channels < 4 or (not image.is_float and image.depth == 24):
        return False

    width, height = image.size
    if width == 0 or height == 0:
        return False

    import numpy as np

    pixels = np.empty(width * height * image.channels, dtype=np.float32)
    image.pixels.foreach_get(pixels)
    return bool((pixels[3 :: image.channels] < (254.5 / 255.0)).any())


def image_source_path(image: Image) -> Path:
    """The absolute filesystem path of `image`'s source file."""
    return Path(bpy.path.abspath(image.filepath, library=image.library))
